"""Build a MODIFIED COPY of the SCInsight Supervisor Agentflow with a readiness gate on the Warehouse branch.

    .venv/bin/python integrations/supplychain/build_readiness_supervisor.py            # defaults below
    .venv/bin/python integrations/supplychain/build_readiness_supervisor.py --source <export.json> --out <copy.json>

What changes in the copy (nothing else is touched):

    5 · Route to a specialist --Warehouse--> 6 · Specialist · Warehouse                       (original)
    5 · Route to a specialist --Warehouse--> 5a · Data readiness --> Ready?
                                                   Ready? --yes--> 6 · Specialist · Warehouse
                                                   Ready? --no---> Stop · data not ready     (copy)

The source export is opened read-only and never written. The copy is NOT imported into Flowise by this script.
Note: in the SCInsight repo the Agentflow JSON files are generated by flowise/scinsight/build-scinsight.cjs; a
permanent change belongs there (see docs/supplychain_integration.md).
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SOURCE = Path(
    "/home/dzoan/Supplychain-AI-agent/flowise/agentflows/SCInsight-Cosmetics-Supervisor-Agentflow-v1.json"
)
DEFAULT_OUT = HERE / "generated" / "SCInsight-Cosmetics-Supervisor-Agentflow-v1.readiness.json"
NODE_JS = HERE / "readiness_node.js"

GATE_FN, GATE_COND, GATE_STOP, GATE_NOTE = (
    "customFunctionAgentflow_tdr",
    "conditionAgentflow_tdr",
    "directReplyAgentflow_tdr",
    "stickyNoteAgentflow_tdr",
)
NEW_STATE = ["tdr_ready", "tdr_message", "tdr_evaluation_id"]


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _node(flow: dict, predicate) -> dict:
    for n in flow["nodes"]:
        if predicate(n):
            return n
    raise SystemExit("expected node not found: the Supervisor export changed; review it before patching")


def _clone(template: dict, new_id: str, label: str, x: float, y: float) -> dict:
    node = copy.deepcopy(template)
    old = template["id"]
    node["id"] = node["data"]["id"] = new_id
    node["data"]["label"] = label
    node["position"] = {"x": x, "y": y}
    node["positionAbsolute"] = {"x": x, "y": y}
    for anchor in node["data"].get("outputAnchors", []):
        anchor["id"] = anchor["id"].replace(old, new_id, 1)
    return node


def _edge(source: dict, handle: str, target: dict, label: str | None = None) -> dict:
    data = {"sourceColor": source["data"]["color"], "targetColor": target["data"]["color"], "isHumanInput": False}
    if label:
        data["edgeLabel"] = label
    return {
        "source": source["id"],
        "sourceHandle": handle,
        "target": target["id"],
        "targetHandle": target["id"],
        "data": data,
        "type": "agentFlow",
        "id": f"{source['id']}-{handle}-{target['id']}-{target['id']}",
    }


def patch(flow: dict, js: str) -> dict:
    flow = copy.deepcopy(flow)
    if any(n["id"] == GATE_FN for n in flow["nodes"]):
        raise SystemExit("the export already contains the readiness gate")
    nodes = {n["id"]: n for n in flow["nodes"]}
    warehouse = _node(
        flow,
        lambda n: (
            n["data"].get("name") == "executeFlowAgentflow"
            and "Warehouse-Agentflow" in str(n["data"]["inputs"].get("executeFlowSelectedFlow", ""))
        ),
    )
    incoming = [e for e in flow["edges"] if e["target"] == warehouse["id"]]
    if len(incoming) != 1 or nodes[incoming[0]["source"]]["data"].get("name") != "conditionAgentflow":
        raise SystemExit("unexpected wiring into the Warehouse specialist; review before patching")
    route_edge = incoming[0]
    router = nodes[route_edge["source"]]

    fn_tpl = _node(flow, lambda n: n["data"].get("name") == "customFunctionAgentflow")
    cond_tpl = _node(flow, lambda n: n["data"].get("name") == "conditionAgentflow" and n["id"] != router["id"])
    stop_tpl = _node(flow, lambda n: n["data"].get("name") == "directReplyAgentflow")
    note_tpl = _node(flow, lambda n: n["data"].get("name") == "stickyNoteAgentflow")

    bottom = max(n["position"]["y"] for n in flow["nodes"]) + 300
    x = warehouse["position"]["x"]
    fn = _clone(fn_tpl, GATE_FN, "5a · Data readiness (taskDataReadiness)", x, bottom)
    fn["data"]["inputs"]["customFunctionInputVariables"] = [
        {"variableName": "question", "variableValue": "{{ question }}"}
    ]
    fn["data"]["inputs"]["customFunctionJavascriptFunction"] = js
    fn["data"]["inputs"]["customFunctionUpdateState"] = [
        {"key": k, "value": "{{ output." + k + " }}"} for k in NEW_STATE
    ]
    cond = _clone(cond_tpl, GATE_COND, "Data ready?", x + 280, bottom)
    cond["data"]["inputs"]["conditions"] = [
        {"type": "string", "value1": "{{ $flow.state.tdr_ready }}", "operation": "equal", "value2": "yes"}
    ]
    cond["data"]["outputAnchors"] = [
        {"id": f"{GATE_COND}-output-{i}", "label": str(i), "name": str(i), "description": str(i)} for i in (0, 1)
    ]
    stop = _clone(stop_tpl, GATE_STOP, "Stop · data not ready", x + 280, bottom + 150)
    stop["data"]["inputs"]["directReplyMessage"] = "{{ $flow.state.tdr_message }}"
    note = _clone(note_tpl, GATE_NOTE, "Sticky Note", x, bottom + 150)
    note["data"]["inputs"]["note"] = (
        "Data readiness gate (taskDataReadiness POST /readiness/check, task warehouse_transfer).\n"
        "Fail closed: unavailable / BLOCKED -> stop before the Warehouse specialist.\n"
        "Preflight only: the SCInsight API still authenticates and scopes every data call.\n"
        "Flowise Variables: tdr_api_url, tdr_demo_user (DEMO identity name, not authentication)."
    )
    flow["nodes"] += [fn, cond, stop, note]

    start = _node(flow, lambda n: n["data"].get("name") == "startAgentflow")
    state = start["data"]["inputs"].setdefault("startState", [])
    state += [{"key": k, "value": ""} for k in NEW_STATE if k not in {s["key"] for s in state}]

    flow["edges"] = [e for e in flow["edges"] if e is not route_edge]
    flow["edges"] += [
        _edge(router, route_edge["sourceHandle"], fn, route_edge["data"].get("edgeLabel", "Warehouse")),
        _edge(fn, f"{GATE_FN}-output-customFunctionAgentflow", cond),
        _edge(cond, f"{GATE_COND}-output-0", warehouse, "ready"),
        _edge(cond, f"{GATE_COND}-output-1", stop, "not ready"),
    ]
    # The only way into the Warehouse specialist is now the "ready" output of the gate.
    into = [e for e in flow["edges"] if e["target"] == warehouse["id"]]
    assert len(into) == 1 and into[0]["sourceHandle"] == f"{GATE_COND}-output-0"
    return flow


def build(source: Path = DEFAULT_SOURCE, out: Path = DEFAULT_OUT) -> dict:
    source, out = Path(source).resolve(), Path(out).resolve()
    if source == out:
        raise SystemExit("refusing to overwrite the original export")
    before = sha256(source)
    flow = json.loads(source.read_text(encoding="utf-8"))
    patched = patch(flow, NODE_JS.read_text(encoding="utf-8"))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(patched, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    if sha256(source) != before:  # defensive: the source must be unchanged
        raise SystemExit("the source export changed during the build")
    return {
        "source": str(source),
        "source_sha256": before,
        "out": str(out),
        "nodes_added": [GATE_FN, GATE_COND, GATE_STOP, GATE_NOTE],
        "state_keys_added": NEW_STATE,
        "edges": f"{len(flow['edges'])} -> {len(patched['edges'])}",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    print(json.dumps(build(args.source, args.out), indent=2))


if __name__ == "__main__":
    main()
