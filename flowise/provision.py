"""Start the dedicated Flowise server and install the Data-Readiness Agentflow (idempotent).

    .venv/bin/python flowise/provision.py        (./start.sh flowise does this)

1. adds missing Flowise secrets and an admin login to .env (random values, never printed)
2. docker compose up (flowise/docker-compose.yml) and waits for Flowise
3. registers the admin (first run) and logs in
4. creates or updates the Agentflow from build_flow.py
"""

from __future__ import annotations

import json
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_flow import NAME, build  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
ENV = ROOT / ".env"
URL = "http://127.0.0.1:3460"
SECRETS = [
    "TDR_FLOWISE_SECRETKEY",
    "TDR_FLOWISE_JWT_SECRET",
    "TDR_FLOWISE_JWT_REFRESH_SECRET",
    "TDR_FLOWISE_SESSION_SECRET",
    "TDR_FLOWISE_TOKEN_HASH_SECRET",
]


def env() -> dict[str, str]:
    values = {}
    if ENV.exists():
        for line in ENV.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                values[k.strip()] = v.strip()
    add = {k: secrets.token_hex(24) for k in SECRETS if not values.get(k)}
    if not values.get("TDR_FLOWISE_ADMIN_EMAIL"):
        add["TDR_FLOWISE_ADMIN_EMAIL"] = "admin@tdr.local"
    if not values.get("TDR_FLOWISE_ADMIN_PASSWORD"):
        add["TDR_FLOWISE_ADMIN_PASSWORD"] = "Tdr-" + secrets.token_urlsafe(12) + "9a!"
    if add:
        with ENV.open("a") as fh:
            fh.write(
                "\n# Flowise (generated by flowise/provision.py)\n" + "".join(f"{k}={v}\n" for k, v in add.items())
            )
        values.update(add)
    return values


class Flowise:
    def __init__(self):
        self.cookies: dict[str, str] = {}

    def call(self, method: str, path: str, body=None, ok=(200, 201)):
        req = urllib.request.Request(
            URL + path,
            data=json.dumps(body).encode() if body is not None else None,
            method=method,
            headers={"Content-Type": "application/json", "x-request-from": "internal"},
        )
        if self.cookies:
            req.add_header("Cookie", "; ".join(f"{k}={v}" for k, v in self.cookies.items()))
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                raw, status, headers = r.read(), r.status, r.headers
        except urllib.error.HTTPError as exc:
            raw, status, headers = exc.read(), exc.code, exc.headers
        for c in headers.get_all("Set-Cookie") or []:
            k, _, rest = c.partition("=")
            self.cookies[k.strip()] = rest.split(";", 1)[0]
        data = json.loads(raw) if raw[:1] in (b"{", b"[") else raw.decode(errors="replace")
        if status not in ok:
            raise RuntimeError(f"{method} {path} -> {status}: {str(data)[:300]}")
        return data


def main() -> int:
    values = env()
    compose = ["docker", "compose", "--env-file", str(ENV), "-f", str(ROOT / "flowise" / "docker-compose.yml")]
    subprocess.run([*compose, "up", "-d"], check=True)
    fw = Flowise()
    for _ in range(90):
        try:
            fw.call("GET", "/api/v1/ping")
            break
        except Exception:  # noqa: BLE001 - not up yet
            time.sleep(2)
    else:
        print("Flowise did not start; see: docker compose -p tdr logs flowise")
        return 1
    email, password = values["TDR_FLOWISE_ADMIN_EMAIL"], values["TDR_FLOWISE_ADMIN_PASSWORD"]
    try:
        fw.call(
            "POST", "/api/v1/account/register", {"user": {"name": "TDR Admin", "email": email, "credential": password}}
        )
    except RuntimeError as exc:
        if "-> 400" not in str(exc):  # 400 = already registered
            raise
    fw.call("POST", "/api/v1/auth/login", {"email": email, "password": password})
    body = {
        "name": NAME,
        "type": "AGENTFLOW",
        "deployed": True,
        "isPublic": False,
        "flowData": json.dumps(build()),
        "category": "taskDataReadiness",
    }
    found = next((f for f in fw.call("GET", "/api/v1/chatflows?type=AGENTFLOW") if f["name"] == NAME), None)
    flow = (
        fw.call("PUT", f"/api/v1/chatflows/{found['id']}", body)
        if found
        else fw.call("POST", "/api/v1/chatflows", body)
    )
    (ROOT / ".data").mkdir(exist_ok=True)
    (ROOT / ".data" / "flowise_flow_id").write_text(flow["id"])
    print(f"Flowise   : {URL}  (login {email}; password = TDR_FLOWISE_ADMIN_PASSWORD in .env)")
    print(f"Agentflow : {URL}/v2/agentcanvas/{flow['id']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
